#!/usr/bin/env bash
set -euo pipefail

BRANCH=${1:?usage: bin/worktree-up.sh <branch>}
SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
MAIN_ROOT=$(dirname "$(git -C "$SCRIPT_DIR" rev-parse --path-format=absolute --git-common-dir)")
WT_DIR="$(dirname "$MAIN_ROOT")/opendealbook-${BRANCH//[^A-Za-z0-9._-]/-}"
ENV_LOCAL=apps/web/.env.local
ENV_HEADER="# AUTO-GENERATED by bin/worktree-up.sh from the main repo's $ENV_LOCAL"
DOCUMENSO_CERT=infra/documenso/cert.p12

cd "$MAIN_ROOT"
if git show-ref --verify --quiet "refs/heads/$BRANCH"; then
  needs_tracking_branch=false
elif git show-ref --verify --quiet "refs/remotes/origin/$BRANCH"; then
  needs_tracking_branch=true
else
  echo "worktree-up: branch $BRANCH exists neither locally nor on origin" >&2
  exit 1
fi

worktree_exists=false
if git worktree list --porcelain | grep -qxF "worktree $WT_DIR"; then
  worktree_exists=true
  checked_out=$(git -C "$WT_DIR" rev-parse --abbrev-ref HEAD)
  if [[ "$checked_out" != "$BRANCH" ]]; then
    echo "worktree-up: $WT_DIR is checked out on $checked_out, not $BRANCH" >&2
    exit 1
  fi
fi

source "$SCRIPT_DIR/worktree-env.sh"
odb_slot_allocate "$WT_DIR" > /dev/null

[[ "$needs_tracking_branch" == false ]] || git branch --track "$BRANCH" "origin/$BRANCH"
[[ "$worktree_exists" == true ]] || git worktree add "$WT_DIR" "$BRANCH"

cd "$WT_DIR"
source "$SCRIPT_DIR/worktree-env.sh"

if [[ ! -f "$ENV_LOCAL" || "$(head -1 "$ENV_LOCAL")" == "$ENV_HEADER" ]]; then
  { echo "$ENV_HEADER"; odb_rewrite_env_file "$MAIN_ROOT/$ENV_LOCAL"; } > "$ENV_LOCAL"
else
  echo "worktree-up: keeping hand-edited $WT_DIR/$ENV_LOCAL"
fi

env_local_value() {
  local key=$1
  grep -m1 "^$key=." "$ENV_LOCAL" | cut -d= -f2- || { echo "worktree-up: $WT_DIR/$ENV_LOCAL has no $key" >&2; return 1; }
}
anon_key=$(env_local_value NEXT_PUBLIC_SUPABASE_ANON_KEY)
service_role_key=$(env_local_value SUPABASE_SERVICE_ROLE_KEY)

if [[ -f "$MAIN_ROOT/$DOCUMENSO_CERT" ]]; then
  cp "$MAIN_ROOT/$DOCUMENSO_CERT" "$DOCUMENSO_CERT"
else
  echo "worktree-up: main repo has no $DOCUMENSO_CERT; Documenso signing will not work in this worktree"
fi

pnpm install
"$SCRIPT_DIR/worktree-start.sh"

(cd apps/web && supabase migration up --db-url "$SUPABASE_DB_URL")

NEXT_PUBLIC_SUPABASE_ANON_KEY=$anon_key SUPABASE_SERVICE_ROLE_KEY=$service_role_key pnpm db:seed

direnv allow "$WT_DIR"
